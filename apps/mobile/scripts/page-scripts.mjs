#!/usr/bin/env node
// Embeds the libraries page scripts run in the page (src/pagescripts/vendor.generated.ts): Mozilla's Readability
// (Apache-2.0) for Reader and Copy as Markdown, and Turndown (MIT) for Markdown. Each is wrapped so it returns its
// export instead of touching the page's globals. Run after updating either: node scripts/page-scripts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = (path) => readFileSync(require.resolve(path), "utf8");
const asModule = (code) => `(() => { const module = { exports: {} }; const exports = module.exports; ${code}\nreturn module.exports; })()`;

const versions = ["@mozilla/readability", "turndown"].map((name) => `${name} ${require(`${name}/package.json`).version}`).join(", ");

const out = `// Generated by scripts/page-scripts.mjs from ${versions}. Don't edit.
// Readability: Apache-2.0, https://github.com/mozilla/readability. Turndown: MIT, https://github.com/mixmark-io/turndown.

/** An expression for Readability's constructor. */
export const READABILITY = ${JSON.stringify(asModule(source("@mozilla/readability/Readability.js")))};

/** An expression for Readability's isProbablyReaderable(document). */
export const READERABLE = ${JSON.stringify(asModule(source("@mozilla/readability/Readability-readerable.js")))};

/** An expression for TurndownService. */
export const TURNDOWN = ${JSON.stringify(asModule(source("turndown/lib/turndown.browser.umd.js")))};
`;

writeFileSync(join(root, "src/pagescripts/vendor.generated.ts"), out);

console.log(`wrote src/pagescripts/vendor.generated.ts (${Math.round(out.length / 1024)} KB, ${versions})`);
