#!/usr/bin/env python3
"""Generate the C ABI call allowlist from NN_ENGINE_CALL declarations."""
from pathlib import Path
import re
import sys
root = Path(__file__).resolve().parents[2]
source = root / 'engine/chromium/src/chrome/browser/bay'
names = sorted({name for header in source.iterdir() if header.suffix in ('.h', '.cc') and header.name != 'nn_dispatch.cc' for name in re.findall(r'^NN_ENGINE_CALL\((nn_[a-z0-9_]+)\)', header.read_text(), re.M)})
header = '''// Generated by scripts/windows/generate-engine-calls.py. Do not edit.
#pragma once
#include <string_view>
namespace bay {
inline bool IsEngineCall(std::string_view name) {
  constexpr std::string_view names[] = {
'''+''.join(f'    "{name}",\n' for name in names)+'''  };
  for (auto allowed : names) if (name == allowed) return true;
  return false;
}
}
'''
target = root / 'engine/nncore/src/bay/core/public/nn_engine_calls.h'
web_facade = root / 'packages/nncore/ios/NNCoreEngineCalls.swift'
web_names = sorted(set(re.findall(r'"(nn_[a-z0-9_]+)"', web_facade.read_text())))
if not web_names or not set(web_names).issubset(names):
    raise SystemExit('Invalid shared JavaScript engine call allowlist')
dispatcher = """// Generated by scripts/windows/generate-engine-calls.py. Do not edit.
#include "chrome/browser/bay/nn_dispatch.h"
#include "chrome/browser/bay/nn_engine.h"

""" + ''.join(f'NN_ENGINE_CALL({name});\n' for name in names) + """
namespace bay {
bool DispatchEngineCall(std::string_view name,
                        const char* profile,
                        const char* args,
                        nn_engine_reply_t reply,
                        void* context) {
  struct Entry {
    std::string_view name;
    nn_engine_call_t call;
  };
  static constexpr Entry calls[] = {
""" + ''.join(f'      {{"{name}", &{name}}},\n' for name in names) + """  };
  for (const auto& entry : calls) {
    if (entry.name == name) {
      entry.call(profile, args, reply, context);
      return true;
    }
  }
  return false;
}
""" + """bool IsWebEngineCall(std::string_view name) {
  static constexpr std::string_view names[] = {
""" + ''.join(f'      "{name}",\n' for name in web_names) + """  };
  for (auto allowed : names) {
    if (name == allowed)
      return true;
  }
  return false;
}
}  // namespace bay
"""
for output, contents in ((target, header), (source / 'nn_dispatch.cc', dispatcher)):
    if '--check' in sys.argv:
        if not output.is_file() or output.read_text() != contents:
            raise SystemExit(f'{output.relative_to(root)} is stale; run scripts/windows/generate-engine-calls.py')
    else:
        output.write_text(contents)
print(f'Engine ABI: {len(names)} callable symbols')
