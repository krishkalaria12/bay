#!/usr/bin/env python3
"""Generate the C ABI call allowlist from NN_ENGINE_CALL declarations."""
from pathlib import Path
import re
import sys
root = Path(__file__).resolve().parents[2]
source = root / 'engine/chromium/src/chrome/browser/bay'
names = sorted({name for header in source.iterdir() if header.suffix in ('.h', '.cc') for name in re.findall(r'^NN_ENGINE_CALL\((nn_[a-z0-9_]+)\)', header.read_text(), re.M)})
header = '''// Generated by scripts/windows/generate-engine-calls.py. Do not edit.
#pragma once
#include <string_view>
namespace bay {
inline bool IsEngineCall(std::string_view name) {
  constexpr std::string_view names[] = {
'''+''.join(f'    "{name}",\n' for name in names)+'''  };
  for (auto allowed : names) if (name == allowed) return true;
  return false;
}
}
'''
target = root / 'engine/nncore/src/bay/core/public/nn_engine_calls.h'
if '--check' in sys.argv:
    if target.read_text() != header:
        raise SystemExit('Engine call allowlist is stale; run scripts/windows/generate-engine-calls.py')
else:
    target.write_text(header)
print(f'Engine ABI: {len(names)} callable symbols')
