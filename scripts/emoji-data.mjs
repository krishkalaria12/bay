#!/usr/bin/env node
// Writes packages/core/src/emojiData.ts, shared by emoji search and the icon picker, from Unicode's emoji-test.txt:
//   curl -fsSLO https://unicode.org/Public/emoji/15.0/emoji-test.txt && node scripts/emoji-data.mjs emoji-test.txt
// Fully qualified emoji only, without skin tones (a picker shows the default), grouped as macOS's picker does:
// smileys and people together, then nature, food, activities, travel, objects, symbols and flags. 15.0 is what
// macOS 14, Bay's oldest, draws.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/emoji-data.mjs <emoji-test.txt>");
  process.exit(1);
}

const GROUPS = [
  { id: "people", title: "Smileys & People", symbol: "face.smiling", from: ["Smileys & Emotion", "People & Body"] },
  { id: "nature", title: "Animals & Nature", symbol: "leaf", from: ["Animals & Nature"] },
  { id: "food", title: "Food & Drink", symbol: "cup.and.saucer", from: ["Food & Drink"] },
  { id: "activities", title: "Activities", symbol: "soccerball", from: ["Activities"] },
  { id: "travel", title: "Travel & Places", symbol: "car", from: ["Travel & Places"] },
  { id: "objects", title: "Objects", symbol: "lightbulb", from: ["Objects"] },
  { id: "symbols", title: "Symbols", symbol: "heart", from: ["Symbols"] },
  { id: "flags", title: "Flags", symbol: "flag", from: ["Flags"] },
];

const byGroup = new Map(GROUPS.map((g) => [g.id, []]));
let group = null;
for (const line of readFileSync(source, "utf8").split("\n")) {
  const heading = line.match(/^# group: (.+)$/);
  if (heading) {
    group = GROUPS.find((g) => g.from.includes(heading[1].trim()))?.id ?? null;
    continue;
  }
  const entry = line.match(/^[0-9A-F ]+; fully-qualified\s+# (\S+) E[\d.]+ (.+)$/);
  if (!entry || !group) continue;
  const [, emoji, name] = entry;
  if (name.includes("skin tone")) continue;
  byGroup.get(group).push(
    `${emoji} ${name
      .replace(/^flag: /, "flag ")
      .replace(/[:,“”]/g, "")
      .toLowerCase()}`,
  );
}

const out = `// Generated by scripts/emoji-data.mjs from Unicode's emoji-test.txt (15.0): don't edit.
// Each emoji is "<emoji> <its name>", the name being what a search finds it by.

export type EmojiGroup = { id: string; title: string; symbol: string; emoji: string[] };

export const EMOJI_GROUPS: EmojiGroup[] = ${JSON.stringify(
  GROUPS.map(({ id, title, symbol }) => ({ id, title, symbol, emoji: byGroup.get(id) })),
  null,
  1,
)};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "../packages/core/src/emojiData.ts");
writeFileSync(target, out);
console.log(`${[...byGroup.values()].reduce((n, list) => n + list.length, 0)} emoji in ${GROUPS.length} groups: ${target}`);
