import ts from "typescript";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const files = ["shell/src/index.tsx", "shell/src/app.ts", "shell/src/system.tsx", "shell/src/live.ts", "nncore/src/native.ts", "nncore/src/chromeUI.ts", "nncore/src/extensions.ts", "nncore/src/swipe.tsx", "nncore/src/WebView.tsx", "nncore/src/NativeWebView.tsx", "sync/src/native.ts", "import/src/index.ts", "shaders/src/index.tsx"];
const modules = {}, views = {}, types = {};
for (const file of files) {
  const filename = path.join(root, "packages", file);
  const source = ts.createSourceFile(filename, readFileSync(filename, "utf8"), ts.ScriptTarget.Latest, true, file.endsWith("tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const aliases = new Map();
  const index = node => {
    if (ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) aliases.set(node.name.text, ts.isTypeAliasDeclaration(node) ? node.type : node);
    ts.forEachChild(node, index);
  };
  index(source);
  types[file] = Object.fromEntries([...aliases].map(([name, node]) => [name, node.getText(source)]));
  const resolve = node => ts.isTypeReferenceNode(node) && aliases.has(node.typeName.getText(source)) ? aliases.get(node.typeName.getText(source)) : node;
  const visit = node => {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && /^require(?:Optional)?Native(?:Module|ViewManager)$/.test(node.expression.text)) {
      const arg = node.arguments[0], type = node.typeArguments?.[0];
      if (arg && ts.isStringLiteral(arg) && type) {
        const name = arg.text;
        if (node.expression.text.endsWith("ViewManager")) views[name] = { source: file, props: type.getText(source) };
        else {
          const spec = resolve(type), methods = {}, events = [], constants = {};
          for (const member of spec.members ?? []) {
            const method = member.name?.getText(source);
            if (!method) continue;
            if (ts.isPropertySignature(member)) {
              constants[method] = member.type?.getText(source) ?? "unknown";
            } else if (method === "addListener") {
              const event = member.parameters?.[0]?.type;
              if (event && ts.isLiteralTypeNode(event) && ts.isStringLiteral(event.literal)) events.push(event.literal.text);
              else if (event && ts.isTypeOperatorNode(event)) {
                const eventType = resolve(event.type);
                for (const prop of eventType.members ?? []) if (prop.name) events.push(prop.name.getText(source));
              } else if (member.typeParameters?.[0]?.constraint) {
                const constraint = member.typeParameters[0].constraint;
                if (ts.isTypeOperatorNode(constraint)) {
                  for (const prop of resolve(constraint.type).members ?? []) if (prop.name) events.push(prop.name.getText(source));
                }
              }
            } else methods[method] = { async: member.type?.getText(source).startsWith("Promise<") ?? false, optional: !!member.questionToken, minArgs: member.parameters?.filter(parameter => !parameter.questionToken && !parameter.initializer && !parameter.dotDotDotToken).length ?? 0, maxArgs: member.parameters?.some(parameter => parameter.dotDotDotToken) ? -1 : member.parameters?.length ?? 0, signature: member.getText(source).replace(/\s+/g, " ") };
          }
          modules[name] = { source: file, methods, events, constants };
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
}
const contract = { version: 1, modules, views, types };
const output = "// Generated by scripts/native-contracts.mjs. Edit the typed native facades, then regenerate.\nexport const nativeContracts = " + JSON.stringify(contract, null, 2) + " as const;\n";
const target = path.join(root, "packages/platform/src/nativeContracts.ts");
const entries = Object.entries(modules).flatMap(([module, contract]) => Object.entries(contract.methods).map(([method, spec]) => `  {"${module}", "${method}", ${spec.async}, ${spec.minArgs}, ${spec.maxArgs}},`));
const header = `// Generated by scripts/native-contracts.mjs. Do not edit.
#pragma once
#include <cstddef>
#include <string_view>

namespace bay::contracts {
inline constexpr int version = 1;
struct Method {
  std::string_view module;
  std::string_view name;
  bool is_async;
  std::size_t min_args;
  int max_args; // -1 permits rest arguments
};
inline constexpr Method methods[] = {
${entries.join("\n")}
};
inline Method const* FindMethod(std::string_view module, std::string_view name) noexcept {
  for (auto const& method : methods) {
    if (method.module == module && method.name == name) return &method;
  }
  return nullptr;
}
} // namespace bay::contracts
`;
const headerTarget = path.join(root, "packages/platform/windows/NativeContracts.g.h");
if (process.argv.includes("--check")) {
  if (readFileSync(headerTarget, "utf8") !== header) throw new Error("Windows native method catalog is stale. Regenerate native contracts.");
  if (readFileSync(target, "utf8") !== output) throw new Error("Native contracts are stale. Run node packages/platform/scripts/native-contracts.mjs");
} else {
  writeFileSync(target, output);
  mkdirSync(path.dirname(headerTarget), { recursive: true });
  writeFileSync(headerTarget, header);
}
console.log(`Native contracts: ${Object.keys(modules).length} modules, ${Object.keys(views).length} views`);
