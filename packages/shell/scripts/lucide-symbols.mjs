const root = process.argv[2];
if (!root) throw new Error("usage: lucide-symbols.mjs <lucide package directory>");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const icon = async (name) => (await import(pathToFileURL(join(root, "dist/esm/icons", `${name}.mjs`)).href)).default;

const lines = [];
for (const [symbol, spec] of Object.entries(SYMBOLS)) {
  const nodes = [];
  for (const part of typeof spec === "string" ? [spec] : spec) {
    if (typeof part === "string") nodes.push(...(await icon(part)));
    else if (Array.isArray(part)) nodes.push(...part);
    else nodes.push(...(await icon(part.inner)).slice(1));
  }
  lines.push(`  ${JSON.stringify(symbol)}: ${JSON.stringify(nodes)},`);
}

const out = new URL("../src/lucideSymbols.web.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by packages/shell/scripts/lucide-symbols.mjs from lucide ${version}. Do not edit.
// Lucide icons, ISC License, Copyright (c) Lucide Icons and Contributors: https://lucide.dev/license
export type SymbolNode = readonly [tag: string, attributes: Readonly<Record<string, string>>];
export const symbolNodes: Readonly<Record<string, readonly SymbolNode[]>> = {
${lines.join("\n")}
};
`,
);
console.log(`${lines.length} symbols → ${out.pathname}`);
